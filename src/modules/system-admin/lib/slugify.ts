/** Turn a typed name into a slug: lowercase, spaces to hyphens, anything else non-alphanumeric dropped. */
export function slugify(value: string) {
    return value
        .toLowerCase()
        .trim()
        .replace(/\s+/g, "-")
        .replace(/[^a-z0-9-]/g, "");
}
